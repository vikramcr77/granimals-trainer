// Builds public/legacy/physio-videos.js from the physio video CSVs.
// Usage: drop part-N.csv in this folder, map any new labels in aliases.json, then run
//   node data/physio-videos/build.mjs
// Fails (and lists them) if a label is unmapped or maps to an exercise missing from phases.js.
import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import { fileURLToPath } from 'node:url'

const dir = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(dir, '../..')
const aliases = JSON.parse(fs.readFileSync(path.join(dir, 'aliases.json'), 'utf8'))

function parseCsv(text) {
  const rows = []
  for (const line of text.trim().split(/\r?\n/).slice(1)) {
    const cells = []
    let cell = ''
    let quoted = false
    for (let i = 0; i < line.length; i++) {
      const ch = line[i]
      if (ch === '"') {
        if (quoted && line[i + 1] === '"') { cell += '"'; i++ } else quoted = !quoted
      } else if (ch === ',' && !quoted) { cells.push(cell); cell = '' } else cell += ch
    }
    cells.push(cell)
    rows.push(cells)
  }
  return rows
}

const files = fs.readdirSync(dir).filter((f) => /^part-\d+\.csv$/.test(f))
  .sort((a, b) => parseInt(a.slice(5)) - parseInt(b.slice(5)))

const log = []
const unmapped = new Set()
let duplicates = 0
let uncounted = 0
for (const file of files) {
  for (const [seq, , , date, , , label] of parseCsv(fs.readFileSync(path.join(dir, file), 'utf8'))) {
    if (/^DUPLICATE\b/i.test(label)) { duplicates++; continue }
    if (!(label in aliases)) { unmapped.add(label); continue }
    const target = aliases[label]
    if (target === null) { uncounted++; continue }
    log.push([Number(seq), date, Array.isArray(target) ? target : [target]])
  }
}

// Every mapped name must exist as an exercise in the rehab phases.
const sandbox = { window: {} }
vm.runInNewContext(fs.readFileSync(path.join(root, 'public/legacy/phases.js'), 'utf8'), sandbox)
const known = new Set(sandbox.window.REHAB_SESSIONS.flatMap((s) => s.ex.map((e) => e.name)))
const missing = [...new Set(log.flatMap((r) => r[2]))].filter((n) => !known.has(n))

if (unmapped.size || missing.length) {
  if (unmapped.size) console.error('Unmapped labels — add them to aliases.json:\n  ' + [...unmapped].join('\n  '))
  if (missing.length) console.error('Mapped to exercises not in phases.js:\n  ' + missing.join('\n  '))
  process.exit(1)
}

log.sort((a, b) => a[0] - b[0])
const out = `/* Generated by data/physio-videos/build.mjs — do not edit by hand.
   Videos Vikram recorded for his physio: [seq, recorded date, exercise name(s) in phases.js]. */
window.PHYSIO_VIDEO_LOG=${JSON.stringify(log)};
`
fs.writeFileSync(path.join(root, 'public/legacy/physio-videos.js'), out)
const names = new Set(log.flatMap((r) => r[2]))
console.log(`${files.length} part(s): ${log.length} videos counted across ${names.size} exercises · ${duplicates} duplicates skipped · ${uncounted} left uncounted`)
